## Quan sát tâm và đối thoại với cảm xúc

Bài đi vào trọng tâm "tầng tâm":

- Quan sát tâm hồn và cảm xúc.
- Nhận ra buồn, giận, lo, sợ, hờn, thương, ghét, yên tâm hay lo lắng.
- Nhìn sâu vào cảm xúc và hỏi: bạn đang lo gì, sợ gì, muốn gì, muốn thêm gì, muốn hơn cái gì.
- Để cảm xúc trả lời.
- Dùng trí tuệ của linh hồn hoặc trí tuệ Vũ Trụ để trả lời.
- Đối đáp đến tận cùng bằng tình yêu thương thuần khiết và trí tuệ thuần khiết.

