## Quan sát trí não và các câu hỏi tinh vi

Bài phân biệt trí não với trí tuệ. Trí não có thể:

- Hỏi nhiều câu rất thông minh, khôn khéo.
- Đưa ra nghi ngờ, lý do, cảnh báo.
- Hỏi như đã kết luận sẵn.
- Dẫn người thực hành đi theo lo sợ nếu không tỉnh thức.

Người thực hành được mời không tranh, không chấp, không bám, mà trả lời bằng trí tuệ khôn ngoan. Linh hồn như người thầy dẫn lại thân, tâm và trí.

Angel AI nên diễn giải rằng trí não có chức năng bảo vệ và phân tích, nhưng đôi khi tạo vòng lặp lo âu. Cần cảm ơn chức năng bảo vệ ấy, rồi kiểm chứng, đặt lại câu hỏi và chọn hành động sáng hơn.

