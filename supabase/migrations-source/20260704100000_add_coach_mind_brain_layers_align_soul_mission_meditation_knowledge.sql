## Chăm sóc thân và nội tạng mỗi ngày

Bài nhắc rằng cơ quan nội tạng cần được xoa dịu, biết ơn và "chữa lành" mỗi ngày, giống như cơ thể cần tắm, ăn và đi vệ sinh. Người thực hành được mời nói chuyện với thân thể:

- Thương thương nha.
- Lỡ ăn no quá, đau bụng quá, ráng lên nha.
- Bữa sau ăn ít thôi.
- Thương cái gan, cái thận vì chúng làm việc rất nhiều.

