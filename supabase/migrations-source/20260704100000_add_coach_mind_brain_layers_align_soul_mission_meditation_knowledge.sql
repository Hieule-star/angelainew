## Bộ não như máy tính và tắt app chạy ngầm

Bài mở đầu bằng hình ảnh rất rõ:

- Bộ não phẳng lặng, không gợn sóng.
- Người thực hành quan sát bộ não từ vị trí linh hồn.
- Mọi suy nghĩ, suy diễn, câu hỏi, thắc mắc, ý kiến và phỏng đoán đều được nhận ra.
- Bộ não được ví như máy tính cần tắt các app/phần mềm chạy ngầm.
- Các app chạy ngầm làm nóng máy, hao bộ nhớ và hao năng lượng.
- Người thực hành là chủ nhân, có thể tắt khi muốn tắt và mở khi muốn mở.

