## Ba luân xa trên và Bi - Trí - Dũng

Bài thiền kích hoạt ba luân xa trên:

- Luân xa vương miện: đại diện cho từ bi và giác ngộ.
- Luân xa thiên nhãn / Thiên Tuệ: đại diện cho trí tuệ, trí huệ và sự minh triết.
- Luân xa cổ họng: đại diện cho dũng cảm, nói sự thật, bảo vệ chân lý và truyền thông điệp chân thành.

